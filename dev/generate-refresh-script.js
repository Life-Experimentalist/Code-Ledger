/**
 * Generates src/vendor/refresh-badges-source.js — the badge refresh script that
 * CodeLedger commits into the user's repository for GitHub Actions to run.
 *
 * The script is bundled from dev/refresh-badges-entry.js, which imports the real
 * scoring and badge modules, so the workflow computes exactly what the extension
 * computes instead of a second copy of the rules that drifts.
 *
 * Run: node dev/generate-refresh-script.js
 * Re-run whenever gamification.js or badge-svg.js changes.
 *
 * `--check` builds without writing and exits 1 if the committed bundle differs
 * from what the sources produce now. test/refresh-script-freshness.test.js runs
 * it, so a change to the scoring modules cannot ship with a stale bundle — the
 * exact drift that had users' nightly workflows recomputing badges with rules
 * the extension had already moved past.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { build } from "esbuild";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const ENTRY = path.join(ROOT, "dev", "refresh-badges-entry.js");
const DEST = path.join(ROOT, "src", "vendor", "refresh-badges-source.js");

const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
  target: "node20",
  // node: builtins stay external; nothing else is allowed to be, so a stray
  // dependency creeping into core fails the build here rather than failing in
  // someone's repository at 4am with no npm install to satisfy it.
  external: ["node:*"],
  legalComments: "none",
  banner: {
    js: [
      "// Generated by CodeLedger. Do not edit — it is overwritten on every sync.",
      "// Recomputes badges/ from index.json so a streak that ends on a day with",
      "// no commits still shows the truth. Run by .github/workflows/codeledger-badges.yml.",
    ].join("\n"),
  },
});

const bundled = result.outputFiles[0].text;

const bare = bundled.match(/^\s*(?:import|export)[^\n]*from\s+["'](?!node:)/m);
if (bare) {
  console.error("bundle kept a non-node import — the script would not run standalone");
  process.exit(1);
}

const output = `// AUTO-GENERATED by dev/generate-refresh-script.js — do not edit manually
// Bundled from dev/refresh-badges-entry.js (src/core/gamification.js + badge-svg.js)
// Re-run: node dev/generate-refresh-script.js
export const REFRESH_BADGES_SCRIPT = ${JSON.stringify(bundled)};
`;

if (process.argv.includes("--check")) {
  const existing = fs.existsSync(DEST) ? fs.readFileSync(DEST, "utf8") : "";
  if (existing !== output) {
    console.error(
      "src/vendor/refresh-badges-source.js is stale — run: node dev/generate-refresh-script.js",
    );
    process.exit(1);
  }
  console.log("refresh-badges-source.js is up to date");
} else {
  fs.mkdirSync(path.dirname(DEST), { recursive: true });
  fs.writeFileSync(DEST, output, "utf8");
  console.log(`refresh-badges-source.js written (${(bundled.length / 1024).toFixed(1)} KB)`);
}
