/**
 * Regenerates src/vendor/vis-network-bundle.js from official npm packages.
 *
 * All sources are official npm releases — no CDN.
 *   vis-network (standalone build, bundles vis-data + injected CSS)
 *     https://www.npmjs.com/package/vis-network
 *
 * The standalone build is the same artifact graphify's exported graph.html
 * loads from unpkg; vendoring it keeps MV3's `script-src 'self'` satisfied
 * and lets a store reviewer read every line that executes.
 *
 * Usage: node dev/generate-vis-vendor.js   (npm run vendor:vis)
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import esbuild from "esbuild";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

function readLockVersion(pkg) {
  try {
    const lock = JSON.parse(fs.readFileSync(path.join(ROOT, "package-lock.json"), "utf8"));
    return lock.packages?.[`node_modules/${pkg}`]?.version || "unknown";
  } catch {
    return "unknown";
  }
}

const visVer = readLockVersion("vis-network");

// Bundle only what GraphView imports: Network + DataSet. esbuild tree-shakes
// the standalone ESM build, which already inlines vis-data and its stylesheet.
const entry = path.join(ROOT, "_tmp_vis_bundle_entry.js");
fs.writeFileSync(entry, `export { Network, DataSet } from "vis-network/standalone";\n`);

const outFile = path.join(ROOT, "src/vendor/vis-network-bundle.js");
try {
  esbuild.buildSync({
    entryPoints: [entry],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2020",
    minify: true,
    outfile: outFile,
    absWorkingDir: ROOT,
  });
} finally {
  fs.rmSync(entry, { force: true });
}

const bundleContent = fs.readFileSync(outFile, "utf8");
const header =
  `// AUTO-GENERATED by dev/generate-vis-vendor.js — do not edit manually\n` +
  `// Source (official npm release, no CDN):\n` +
  `//   vis-network@${visVer} (standalone build, includes vis-data + CSS)\n` +
  `//   https://www.npmjs.com/package/vis-network/v/${visVer}\n` +
  `// Bundled with esbuild from official npm packages.\n\n`;
fs.writeFileSync(outFile, header + bundleContent);

const kb = (fs.statSync(outFile).size / 1024).toFixed(0);
console.log(`✓ vendor/vis-network-bundle.js → vis-network@${visVer} (${kb}KB)`);
