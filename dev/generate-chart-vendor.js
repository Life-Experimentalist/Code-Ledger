/**
 * Generates src/vendor/chart-source.js by reading the bundled chart.umd.min.js
 * from node_modules and exporting it as an inline string constant.
 *
 * Run: node dev/generate-chart-vendor.js
 * Re-run whenever chart.js is upgraded in package.json.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const SRC = path.join(ROOT, "node_modules", "chart.js", "dist", "chart.umd.min.js");
const DEST = path.join(ROOT, "src", "vendor", "chart-source.js");

if (!fs.existsSync(SRC)) {
  console.error("chart.js not found in node_modules — run npm install first");
  process.exit(1);
}

const content = fs.readFileSync(SRC, "utf8");
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "node_modules", "chart.js", "package.json"), "utf8"));
const version = pkg.version;

// JSON.stringify safely escapes all special characters (backticks, quotes, etc.)
const output = `// AUTO-GENERATED by dev/generate-chart-vendor.js — do not edit manually
// Source: node_modules/chart.js@${version}/dist/chart.umd.min.js
// Re-run: node dev/generate-chart-vendor.js
export const CHART_JS_INLINE = ${JSON.stringify(content)};
`;

fs.writeFileSync(DEST, output, "utf8");
console.log(`chart-source.js written (${(content.length / 1024).toFixed(1)} KB) from chart.js@${version}`);
