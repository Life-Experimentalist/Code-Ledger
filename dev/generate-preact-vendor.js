/**
 * Regenerates src/vendor/preact-bundle.js from official npm packages.
 *
 * All sources are official npm releases — no CDN.
 *   preact@10.29.1       https://www.npmjs.com/package/preact/v/10.29.1
 *   preact/hooks@10.29.1 (bundled within the preact package)
 *   htm@3.1.1            https://www.npmjs.com/package/htm/v/3.1.1
 *
 * Also updates vendor/preact.js and vendor/htm.js with exact npm copies.
 *
 * Usage: node dev/generate-preact-vendor.js
 */

import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

function readLockVersion(pkg) {
  try {
    const lock = JSON.parse(fs.readFileSync(path.join(ROOT, "package-lock.json"), "utf8"));
    return lock.packages?.[`node_modules/${pkg}`]?.version || "unknown";
  } catch {
    return "unknown";
  }
}

const preactVer = readLockVersion("preact");
const htmVer = readLockVersion("htm");

// ── 1. vendor/preact.js ──────────────────────────────────────────────────────
const preactSrc = fs.readFileSync(
  path.join(ROOT, "node_modules/preact/dist/preact.module.js"),
  "utf8",
);
fs.writeFileSync(
  path.join(ROOT, "src/vendor/preact.js"),
  `// SOURCE: node_modules/preact@${preactVer}/dist/preact.module.js\n` +
    `// npm: https://www.npmjs.com/package/preact/v/${preactVer}\n` +
    `// Official: https://github.com/preactjs/preact\n` +
    `// Unmodified copy from npm package. Re-run: node dev/generate-preact-vendor.js\n\n` +
    preactSrc,
);
console.log(`✓ vendor/preact.js → preact@${preactVer} (official npm, no CDN)`);

// ── 2. vendor/htm.js ─────────────────────────────────────────────────────────
const htmSrc = fs.readFileSync(path.join(ROOT, "node_modules/htm/dist/htm.module.js"), "utf8");
fs.writeFileSync(
  path.join(ROOT, "src/vendor/htm.js"),
  `// SOURCE: node_modules/htm@${htmVer}/dist/htm.module.js\n` +
    `// npm: https://www.npmjs.com/package/htm/v/${htmVer}\n` +
    `// Official: https://github.com/developit/htm\n` +
    `// Unmodified copy from npm package. Re-run: node dev/generate-preact-vendor.js\n\n` +
    htmSrc,
);
console.log(`✓ vendor/htm.js → htm@${htmVer} (official npm, no CDN)`);

// ── 3. vendor/preact-bundle.js ───────────────────────────────────────────────
// Bundle preact + preact/hooks + htm into one ESM file so extension pages
// can import from a single path without a module bundler or import maps.
const entry = path.join(ROOT, "_tmp_preact_bundle_entry.js");
fs.writeFileSync(
  entry,
  `export { h, render, Component, Fragment, cloneElement, createContext, createRef,
           hydrate, isValidElement, options, toChildArray } from "preact";
export { useState, useReducer, useEffect, useLayoutEffect, useRef, useCallback,
         useMemo, useContext, useDebugValue, useId, useImperativeHandle } from "preact/hooks";
export { default as htm } from "htm";
`,
);

const outFile = path.join(ROOT, "src/vendor/preact-bundle.js");
try {
  execFileSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    [
      "esbuild",
      entry,
      "--bundle",
      "--format=esm",
      "--platform=browser",
      "--target=es2020",
      "--minify",
      `--outfile=${outFile}`,
    ],
    { cwd: ROOT, encoding: "utf8" },
  );
} finally {
  fs.rmSync(entry, { force: true });
}

const bundleContent = fs.readFileSync(outFile, "utf8");
const header =
  `// AUTO-GENERATED by dev/generate-preact-vendor.js — do not edit manually\n` +
  `// Sources (official npm releases, no CDN):\n` +
  `//   preact@${preactVer}       https://www.npmjs.com/package/preact/v/${preactVer}\n` +
  `//   preact/hooks@${preactVer} (hooks subpath bundled within preact package)\n` +
  `//   htm@${htmVer}            https://www.npmjs.com/package/htm/v/${htmVer}\n` +
  `// Bundled with esbuild from official npm packages.\n\n`;
fs.writeFileSync(outFile, header + bundleContent);

const lines = fs.readFileSync(outFile, "utf8").split("\n").length;
console.log(`✓ vendor/preact-bundle.js → preact@${preactVer} + htm@${htmVer} (${lines} lines)`);
